#!/bin/bash
# Builds data/style/unidesk-dark.css: the GTK 3.24 Adwaita theme (dark variant) with the Unidesk palette.
# The application loads it over Adwaita (remmina_theme.c), so widgets keep the Adwaita shapes and
# get the colours of packaging/theme/_colors.scss.
#
# Needs sassc and the sources of the GTK version the AppImage bundles (Ubuntu 22.04: 3.24.33,
# https://download.gnome.org/sources/gtk+/3.24/gtk+-3.24.33.tar.xz,
# sha256 588b06522e25d1579e989b6f9d8a1bdbf2fe13cde01a04e904ff346a225e7801).
# Usage: bash packaging/theme/build-theme.sh <gtk+-3.24.33.tar.xz | GTK source dir> [output.css]
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=${2:-$HERE/../../data/style/unidesk-dark.css}
GTK=${1:?GTK 3.24 tarball or source dir}
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

if [ -f "$GTK" ]; then
  tar -xJf "$GTK" -C "$WORK" --strip-components=1 --wildcards '*/gtk/theme/Adwaita/*'
  ADW="$WORK/gtk/theme/Adwaita"
else
  ADW="$GTK/gtk/theme/Adwaita"
fi
mkdir "$WORK/adw"
cp "$ADW"/_*.scss "$WORK/adw/"
cp "$HERE/_colors.scss" "$HERE/unidesk-dark.scss" "$WORK/adw/"

# Suggested buttons get their own text colour ($suggested_fg_color, dark on the bright accent):
# Adwaita hard-codes white, which is 2.4:1 on #3daee9. Destructive buttons keep white.
C="$WORK/adw/_common.scss"
sed -i -E 's/@each \$b_type, \$b_color in \(suggested-action, \$suggested_bg_color\),/@each $b_type, $b_color, $b_fg in (suggested-action, $suggested_bg_color, $suggested_fg_color),/' "$C"
sed -i -E 's/\(destructive-action, \$destructive_color\) \{/(destructive-action, $destructive_color, white) {/' "$C"
sed -i -E '/@each \$b_type, \$b_color, \$b_fg in/,/\.osd & \{/ s/\$b_color, white\)/$b_color, $b_fg)/g' "$C"
n=$(grep -c '\$b_color, \$b_fg)' "$C" || true)
if [ "$n" -lt 5 ]; then echo "patch of _common.scss failed ($n replacements)" >&2; exit 1; fi

# Header bar in the window colour like LACT: Adwaita fills it from the background darkened by 10 %
# (and lightens the dark variant by 4-6 % again), which on #202326 gives a near-black bar.
sed -i -E 's/@include headerbar_fill\(darken\(\$bg_color, 10%\)\);/@include headerbar_fill(darken($headerbar_color, 5%));/' "$C"
grep -q 'headerbar_fill(darken(\$headerbar_color, 5%))' "$C" || { echo "patch of the header bar failed" >&2; exit 1; }

# Notebook pages (Preferences, connection editor) on the window colour like LACT's pages;
# lists and entries keep the darker view colour, as in Breeze.
sed -i -E '/> stack:not\(:only-child\) \{/{n;s/background-color: \$base_color;/background-color: $bg_color;/}' "$C"
grep -A1 '> stack:not(:only-child) {' "$C" | grep -q 'background-color: \$bg_color;' || { echo "patch of the notebook pages failed" >&2; exit 1; }

sassc -M -t expanded "$WORK/adw/unidesk-dark.scss" "$WORK/unidesk-dark.css"

# Assets (check marks, bullets…) are referenced relative to the theme file; point them at the
# copies GTK keeps in its own resources.
mkdir -p "$(dirname "$OUT")"
{
  echo "/* Unidesk dark theme. GENERATED by packaging/theme/build-theme.sh from the GTK $(basename "$GTK")"
  echo "   Adwaita sources and packaging/theme/_colors.scss; do not edit by hand. */"
  sed -E 's#url\("assets/#url("resource:///org/gtk/libgtk/theme/Adwaita/assets/#g' "$WORK/unidesk-dark.css"
} > "$OUT"
echo "written: $OUT ($(wc -c < "$OUT") bytes, $n suggested-button rules patched)"
